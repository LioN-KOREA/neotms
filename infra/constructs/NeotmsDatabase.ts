// The Aurora Serverless v2 PostgreSQL cluster, reached over the RDS Data API.
//
// Two decisions in here carry most of the project's cost and operability, and both are easy to undo
// by accident, so they are written down next to the code that depends on them.
//
// ## The VPC has no NAT Gateway, and the Lambda is not in the VPC
//
// Aurora requires a VPC; a Lambda does not have to join it. Because the Data API is an HTTPS service
// addressed with SigV4, the function reaches the database from outside the VPC entirely. That buys
// three things at once:
//
//   * No NAT Gateway. A NAT Gateway is ~$43/month before a byte flows through it, and it was the
//     single largest line item in the cost model - larger than the database itself at a 0.5 ACU
//     floor. On a budget of ₩100,000/month it is not affordable.
//   * Free egress to the account system. The sign-in flow calls the LPX OIDC discovery, token and
//     userInfo endpoints. From inside a private subnet those calls need a NAT Gateway (per-GB
//     charges) or an interface endpoint per service; from outside the VPC they are ordinary internet
//     egress, which Lambda does not bill.
//   * No ENI cold start, and no ENI limit. VPC-attached Lambdas share a pool of Hyperplane ENIs;
//     outside the VPC that whole failure mode does not exist.
//
// So the subnets below are PRIVATE_ISOLATED with `natGateways: 0`. If someone later adds a VPC
// Lambda, CDK will quietly add a NAT Gateway to give it egress and the bill will move by ~$43/month
// with no other visible change. That is the trap this comment exists to flag.
//
// ## The Data API is the only path in
//
// No connection pooling, no RDS Proxy ($15/month per endpoint), no idle connection held by a warm
// container. The Data API's own limits are what the application has to be written around, and they
// are handled in the backend's RdsDataUtils:
//
//   * 1 MiB per result set - RETURNED, not scanned. Keyset pagination keeps every page well inside
//     it; the one genuinely large read (report export) goes through `aws_s3.query_export_to_s3`
//     instead, which is why the export bucket below is SSE-KMS and not SSE-S3.
//   * A resuming cluster answers with a 400-class `DatabaseResumingException`, which the AWS SDKs do
//     NOT retry, because 400s are not retryable in general. An explicit retry wrapper is mandatory.

import * as cdk from "aws-cdk-lib/core";
import * as ec2 from "aws-cdk-lib/aws-ec2";
import * as iam from "aws-cdk-lib/aws-iam";
import * as kms from "aws-cdk-lib/aws-kms";
import * as logs from "aws-cdk-lib/aws-logs";
import * as rds from "aws-cdk-lib/aws-rds";
import * as s3 from "aws-cdk-lib/aws-s3";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import { Construct } from "constructs";
import { NeotmsStageConfig } from "../config/NeotmsConfig.js";

export interface NeotmsDatabaseProps {
  readonly config: NeotmsStageConfig;
  /** Bucket the cluster may write report exports into. Must be SSE-KMS; see below. */
  readonly exportBucket: s3.IBucket;
  readonly exportKey: kms.IKey;
}

export class NeotmsDatabase extends Construct {
  public readonly cluster: rds.DatabaseCluster;
  public readonly databaseName = "neotms";
  /** Writer endpoint credential. Generated by CDK; nobody ever sees or types it. */
  public readonly secret: secretsmanager.ISecret;
  public readonly vpc: ec2.Vpc;

  constructor(scope: Construct, id: string, props: NeotmsDatabaseProps) {
    super(scope, id);
    const { config } = props;

    /*
     * Isolated subnets in two AZs, and nothing else.
     *
     * Two AZs is Aurora's minimum for a subnet group. There is no public subnet and no internet
     * gateway: nothing in this VPC needs to reach the internet, and nothing on the internet needs to
     * reach it. `natGateways: 0` is the load-bearing line - see the header.
     */
    this.vpc = new ec2.Vpc(this, "Vpc", {
      vpcName: `${config.resourcePrefix}-vpc`,
      maxAzs: 2,
      natGateways: 0,
      subnetConfiguration: [
        { name: "db", subnetType: ec2.SubnetType.PRIVATE_ISOLATED, cidrMask: 24 },
      ],
      // The Data API does not traverse the VPC, so there is no in-VPC DNS consumer to serve. Left
      // on anyway because it costs nothing and a future bastion would need it.
      enableDnsHostnames: true,
      enableDnsSupport: true,
    });

    /*
     * Extensions have to be declared before they can be created.
     *
     * `pg_bigm` is not in Aurora's default `shared_preload_libraries`, and `CREATE EXTENSION pg_bigm`
     * fails until it is. It also cannot be added without a reboot, so it belongs here rather than in
     * a migration script.
     *
     * Why pg_bigm rather than pg_trgm for the Korean columns: pg_trgm indexes 3-grams, and a
     * 2-character Korean search term (삼성, 번역, 한글 - overwhelmingly common in customer and project
     * names) produces no trigram at all. The planner then silently falls back to a sequential scan,
     * so the index appears to exist and does nothing. pg_bigm indexes 2-grams and handles them.
     * pg_trgm is still loaded, for the ASCII identifier columns where 3-grams are correct.
     */
    const parameterGroup = new rds.ParameterGroup(this, "ClusterParameterGroup", {
      engine: rds.DatabaseClusterEngine.auroraPostgres({
        version: rds.AuroraPostgresEngineVersion.VER_16_13,
      }),
      description: "NEOTMS cluster parameters - pg_bigm preload and statement logging",
      parameters: {
        shared_preload_libraries: "pg_stat_statements,pg_bigm",
        /*
         * Log any statement over a second. The legacy system's pathology was unindexed `nvarchar`
         * predicates and deep `OFFSET` paging, and the only way to know whether it has been
         * reintroduced is to have the slow ones named in the log from day one.
         */
        log_min_duration_statement: "1000",
        "pg_bigm.enable_recheck": "on",
        /*
         * 2 is the default and the lowest pg_bigm supports. Spelled out because the whole reason this
         * extension is here is the 2-gram minimum, and a well-meaning tune to 3 would re-create the
         * pg_trgm blind spot it was chosen to avoid.
         */
        "pg_bigm.gin_key_limit": "0",
      },
    });

    /*
     * Encryption key for the cluster and its snapshots.
     *
     * A customer-managed key rather than the AWS-managed `aws/rds` one, because snapshot sharing and
     * key revocation both need a key whose policy this account controls. ~$1/month.
     */
    const storageKey = new kms.Key(this, "StorageKey", {
      alias: `${config.resourcePrefix}-db`,
      description: "NEOTMS Aurora storage and snapshot encryption",
      enableKeyRotation: true,
      removalPolicy: config.protectData ? cdk.RemovalPolicy.RETAIN : cdk.RemovalPolicy.DESTROY,
    });

    /*
     * The role the CLUSTER assumes to write report exports - not the Lambda's role.
     *
     * `aws_s3.query_export_to_s3` runs inside PostgreSQL, so the PutObject is made by the cluster.
     * The bucket must be SSE-KMS, not SSE-S3: with SSE-S3 the export fails, and the error does not
     * say why. Hence the explicit `kms:GenerateDataKey` grant below.
     */
    const exportRole = new iam.Role(this, "S3ExportRole", {
      assumedBy: new iam.ServicePrincipal("rds.amazonaws.com"),
      description: "Lets the NEOTMS cluster write report exports with aws_s3.query_export_to_s3",
    });
    props.exportBucket.grantWrite(exportRole);
    props.exportKey.grantEncryptDecrypt(exportRole);

    this.cluster = new rds.DatabaseCluster(this, "Cluster", {
      clusterIdentifier: `${config.resourcePrefix}-cluster`,
      /*
       * Pinned to 16.x on purpose.
       *
       * The Data API's supported-version table is per-engine-major and has no PostgreSQL 18 column.
       * Taking the newest available major would produce a cluster that builds, deploys, and then
       * rejects every `ExecuteStatement` with a message about the Data API not being supported - at
       * which point the only fix is a major-version migration. Raise this only after checking that
       * table, not because a newer number exists.
       */
      engine: rds.DatabaseClusterEngine.auroraPostgres({
        version: rds.AuroraPostgresEngineVersion.VER_16_13,
      }),
      parameterGroup,
      defaultDatabaseName: this.databaseName,
      /*
       * The Data API. Without this the cluster is only reachable over a socket from inside the VPC,
       * which would force the Lambda into the VPC and drag the NAT Gateway back in with it.
       */
      enableDataApi: true,
      vpc: this.vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PRIVATE_ISOLATED },
      storageEncrypted: true,
      storageEncryptionKey: storageKey,
      credentials: rds.Credentials.fromGeneratedSecret("neotms_app", {
        secretName: `${config.resourcePrefix}/db/app`,
        // Dropped from the generated password: the Data API passes the secret ARN rather than the
        // password itself, but psql-via-bastion during the migration does not, and these three
        // characters are the ones that break shell quoting and JDBC URLs.
        excludeCharacters: "\"@/\\'",
      }),
      serverlessV2MinCapacity: config.capacity.businessHoursMinAcu,
      serverlessV2MaxCapacity: config.capacity.maxAcu,
      serverlessV2AutoPauseDuration: cdk.Duration.seconds(config.capacity.secondsUntilAutoPause),
      /*
       * A single writer, no reader.
       *
       * Accepted deliberately (Q13): a failover is ~60 seconds of unavailability, and for an
       * in-house tool used by a few dozen staff in one time zone that is cheaper than a second
       * instance running all day. A reader can be added later without touching the application,
       * because the Data API addresses the cluster rather than an instance.
       */
      writer: rds.ClusterInstance.serverlessV2("writer", {
        // The cluster cannot pause while a minor-version upgrade is pending, so leave this on and
        // let it happen inside the maintenance window below.
        autoMinorVersionUpgrade: true,
        /*
         * Repeated from the cluster-level setting below, which is not redundant.
         *
         * An instance that does not state its own value defaults to "off", and CDK then warns that
         * the cluster-level setting will override it. The outcome is the same either way, but a
         * synth that prints a warning on every run is a synth whose warnings stop being read - and
         * the next one may be about the NAT Gateway.
         */
        enablePerformanceInsights: true,
        performanceInsightRetention: rds.PerformanceInsightRetention.DEFAULT,
      }),
      /*
       * `s3ExportRole`, not `s3ExportBuckets` - CDK rejects both together, and the role is the one
       * that lets the KMS grant be attached. `s3ExportBuckets` builds a role with bucket permissions
       * only, which is exactly the SSE-KMS failure described above.
       */
      s3ExportRole: exportRole,
      backup: {
        retention: cdk.Duration.days(config.protectData ? 14 : 1),
        // 17:00 UTC = 02:00 KST. Inside the off-hours window, so the cluster is woken by the backup
        // rather than by a user.
        preferredWindow: "17:00-17:30",
      },
      // Sunday 18:00 UTC = Monday 03:00 KST.
      preferredMaintenanceWindow: "Sun:18:00-Sun:19:00",
      /*
       * Query Insights, not Enhanced Monitoring.
       *
       * Performance Insights at 7-day retention is free and is the tool that would have found the
       * legacy system's unindexed scans. Enhanced Monitoring bills per metric per instance and tells
       * you about the OS, which on a serverless instance nobody can log into is of little use.
       */
      enablePerformanceInsights: true,
      performanceInsightRetention: rds.PerformanceInsightRetention.DEFAULT,
      cloudwatchLogsExports: ["postgresql"],
      cloudwatchLogsRetention: config.protectData
        ? logs.RetentionDays.SIX_MONTHS
        : logs.RetentionDays.ONE_MONTH,
      deletionProtection: config.protectData,
      removalPolicy: config.protectData ? cdk.RemovalPolicy.RETAIN : cdk.RemovalPolicy.DESTROY,
    });

    this.secret = this.cluster.secret!;
  }

  /**
   * Lets a function call the Data API and read the credential.
   *
   * Both halves are required and they are separate permissions: `rds-data:*` authorises the call,
   * `secretsmanager:GetSecretValue` authorises the `secretArn` named in it. Granting only the first
   * produces an AccessDenied that names the secret, which reads like a secret problem rather than a
   * missing grant.
   */
  public grantDataApi(grantee: iam.IGrantable): void {
    this.cluster.grantDataApiAccess(grantee);
  }
}
