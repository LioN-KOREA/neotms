-- 016: '완료 업무' 시트 — 나의 업무에서 아카이빙한 행의 보관함 (팀장님 2026-11-26).
--
-- [아카이빙] 을 누르면 진행 상태가 '납품 완료' 인 행(작업 행·직접 만든 빈 줄 모두)이 여기로 옮겨진다.
--   * cells      : 옮길 때 화면에 보이던 그대로 — { 열 키: { t: 보이는 글자, s: 서식 } }. 읽기 전용 보관이라
--                  수식 결과·날짜 서식까지 '보이던 글자' 를 남긴다. 열 구성은 나의 업무의 열 설정을 따른다.
--   * job_id     : 작업 행이면 그 작업(나의 업무에서는 pm_sheet_row.hidden 으로 빠진다), 빈 줄이면 NULL.
--   * handover_at: 정렬과 'yyyy년 mm월' 묶음의 기준(인계일). 빈 줄에 인계일이 없으면 옮긴 때.
--
-- 다시 실행해도 된다.

CREATE TABLE IF NOT EXISTS pm_sheet_archive (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id    bigint NOT NULL REFERENCES staff(id),
  job_id      bigint REFERENCES job(id),
  handover_at timestamptz,
  cells       jsonb NOT NULL DEFAULT '{}'::jsonb,
  row_style   jsonb NOT NULL DEFAULT '{}'::jsonb,
  archived_at timestamptz NOT NULL DEFAULT now(),
  archived_by text,
  CHECK (pg_column_size(cells) <= 65536 AND pg_column_size(row_style) <= 4096)
);

CREATE INDEX IF NOT EXISTS pm_sheet_archive_staff_idx ON pm_sheet_archive (staff_id, handover_at);

COMMENT ON TABLE pm_sheet_archive IS
  'Rows a PM archived from their work sheet ("완료 업무"). A snapshot of what the row showed when archived (cells: column key -> {t: shown text, s: style}); read-only for now. job_id is the job for a job row (that job is hidden from the live sheet), NULL for a free row.';
