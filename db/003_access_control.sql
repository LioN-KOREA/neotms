CREATE INDEX IF NOT EXISTS ix_staff_attribute_attr ON staff_attribute (attribute);

CREATE OR REPLACE FUNCTION neotms_known_permissions()
RETURNS SETOF text
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $fn$
  SELECT m[1]
    FROM pg_constraint c,
         LATERAL regexp_matches(pg_get_constraintdef(c.oid), '''([A-Z_]+)''', 'g') AS m
   WHERE c.conrelid = 'sys_role_permission'::regclass
     AND c.conname  = 'ck_sys_role_permission';
$fn$;

COMMENT ON FUNCTION neotms_known_permissions() IS
  'Every permission name the CHECK on sys_role_permission allows, one per row. The single SQL-side '
  'reading of the vocabulary; sys_role_grant_all_permissions() grants from it.';

CREATE OR REPLACE FUNCTION sys_role_grant_all_permissions(p_role_code text)
RETURNS integer
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_role_id bigint;
  v_count   integer;
BEGIN
  SELECT id INTO v_role_id FROM sys_role WHERE role_code = p_role_code;
  IF v_role_id IS NULL THEN
    RAISE EXCEPTION
      'sys_role_grant_all_permissions: no sys_role row has role_code = %. '
      'Apply db/002_initial_seeding.sql, or check the spelling.', p_role_code;
  END IF;

  INSERT INTO sys_role_permission (role_id, permission, created_by)
  SELECT v_role_id, p.permission, 'neotms-bootstrap'
    FROM neotms_known_permissions() AS p(permission)
  ON CONFLICT (role_id, permission) DO NOTHING;

  SELECT count(*) INTO v_count
    FROM sys_role_permission
   WHERE role_id = v_role_id;

  RETURN v_count;
END;
$fn$;

COMMENT ON FUNCTION sys_role_grant_all_permissions(text) IS
  'Grants one role every permission this build knows. Idempotent; returns the number the role now '
  'holds. Re-run it after anything that adds to the permission vocabulary, because grants written '
  'once do not cover permissions added later and the resulting failure is a silent refusal rather '
  'than an error.';


-- =====================================================================
-- 2. Translate the existing matrix into permission rows
-- =====================================================================
--
-- One row of sys_role_auth becomes up to five permission rows. The mapping
-- below is (menu_id, flag) -> permission name, and it is written out in
-- full rather than derived, because three menus do not have five actions:
--
--   * REPORT and the two DASHBOARD menus are read-only. A role holding
--     create or delete on them held a right the application never offered,
--     so there is nothing to carry across and nothing is lost.
--   * STAFF has no create and no delete. The route table has never had
--     either -- a staff row needs an account-system subject to be usable,
--     and access is ended by deactivating a person, not by deleting their
--     history. Those two flags are likewise dropped.
--
-- Everything else maps one for one. `ON CONFLICT DO NOTHING` makes the
-- whole section re-runnable.
--
-- `a.active` is filtered because the legacy column was nvarchar(20) and
-- the ETL may have loaded anything; the schema's rule is that only an
-- explicit 'N' means inactive, and the boolean already reflects that.

INSERT INTO sys_role_permission (role_id, permission, created_by)
SELECT DISTINCT a.role_id, v.permission, 'neotms-003-migration'
  FROM sys_role_auth a
  JOIN (VALUES
    ('PROJECT',         1, 'NEOTMS_PERMISSION_PROJECT_READ'),
    ('PROJECT',         2, 'NEOTMS_PERMISSION_PROJECT_CREATE'),
    ('PROJECT',         3, 'NEOTMS_PERMISSION_PROJECT_UPDATE'),
    ('PROJECT',         4, 'NEOTMS_PERMISSION_PROJECT_DELETE'),
    ('JOB',             1, 'NEOTMS_PERMISSION_JOB_READ'),
    ('JOB',             2, 'NEOTMS_PERMISSION_JOB_CREATE'),
    ('JOB',             3, 'NEOTMS_PERMISSION_JOB_UPDATE'),
    ('JOB',             4, 'NEOTMS_PERMISSION_JOB_DELETE'),
    ('PURCHASE_ORDER',  1, 'NEOTMS_PERMISSION_PO_READ'),
    ('PURCHASE_ORDER',  2, 'NEOTMS_PERMISSION_PO_CREATE'),
    ('PURCHASE_ORDER',  3, 'NEOTMS_PERMISSION_PO_UPDATE'),
    ('PURCHASE_ORDER',  4, 'NEOTMS_PERMISSION_PO_DELETE'),
    ('CUSTOMER',        1, 'NEOTMS_PERMISSION_CUSTOMER_READ'),
    ('CUSTOMER',        2, 'NEOTMS_PERMISSION_CUSTOMER_CREATE'),
    ('CUSTOMER',        3, 'NEOTMS_PERMISSION_CUSTOMER_UPDATE'),
    ('CUSTOMER',        4, 'NEOTMS_PERMISSION_CUSTOMER_DELETE'),
    ('TRANSLATOR',      1, 'NEOTMS_PERMISSION_TRANSLATOR_READ'),
    ('TRANSLATOR',      2, 'NEOTMS_PERMISSION_TRANSLATOR_CREATE'),
    ('TRANSLATOR',      3, 'NEOTMS_PERMISSION_TRANSLATOR_UPDATE'),
    ('TRANSLATOR',      4, 'NEOTMS_PERMISSION_TRANSLATOR_DELETE'),
    ('PAYMENT',         1, 'NEOTMS_PERMISSION_INVOICE_READ'),
    ('PAYMENT',         2, 'NEOTMS_PERMISSION_INVOICE_CREATE'),
    ('PAYMENT',         3, 'NEOTMS_PERMISSION_INVOICE_UPDATE'),
    ('PAYMENT',         4, 'NEOTMS_PERMISSION_INVOICE_DELETE'),
    ('MAINTENANCE',     1, 'NEOTMS_PERMISSION_MAINTENANCE_READ'),
    ('MAINTENANCE',     2, 'NEOTMS_PERMISSION_MAINTENANCE_CREATE'),
    ('MAINTENANCE',     3, 'NEOTMS_PERMISSION_MAINTENANCE_UPDATE'),
    ('MAINTENANCE',     4, 'NEOTMS_PERMISSION_MAINTENANCE_DELETE'),
    ('REPORT',          1, 'NEOTMS_PERMISSION_REPORT_READ'),
    ('DASHBOARD_SALES', 1, 'NEOTMS_PERMISSION_DASHBOARD_SALES_READ'),
    ('DASHBOARD_PM',    1, 'NEOTMS_PERMISSION_DASHBOARD_PM_READ'),
    ('STAFF',           1, 'NEOTMS_PERMISSION_STAFF_READ'),
    ('STAFF',           3, 'NEOTMS_PERMISSION_STAFF_UPDATE')
  ) AS v(menu_id, flag, permission)
    ON v.menu_id = a.menu_id
 WHERE a.active
   AND CASE v.flag
         WHEN 1 THEN a.role_1
         WHEN 2 THEN a.role_2
         WHEN 3 THEN a.role_3
         WHEN 4 THEN a.role_4
         ELSE false
       END
ON CONFLICT (role_id, permission) DO NOTHING;

-- The two that had no grant of their own, given to exactly the people who
-- could already perform the action. See the header: this preserves
-- behaviour, and section 6 is where it gets narrowed deliberately.
INSERT INTO sys_role_permission (role_id, permission, created_by)
SELECT a.role_id, 'NEOTMS_PERMISSION_PO_APPROVE', 'neotms-003-migration'
  FROM sys_role_auth a
 WHERE a.active AND a.menu_id = 'PAYMENT' AND a.role_3
ON CONFLICT (role_id, permission) DO NOTHING;

INSERT INTO sys_role_permission (role_id, permission, created_by)
SELECT a.role_id, 'NEOTMS_PERMISSION_PROJECT_EMAIL', 'neotms-003-migration'
  FROM sys_role_auth a
 WHERE a.active AND a.menu_id = 'PROJECT' AND a.role_1
ON CONFLICT (role_id, permission) DO NOTHING;

-- NEOTMS_PERMISSION_PO_EMAIL is granted to no ORDINARY role. There is no
-- feature behind it yet, so granting it would be granting the ability to
-- do nothing -- and it would then look, to the next reader of the admin
-- screen, like a right somebody deliberately handed out.
--
-- The superuser role is the exception, below.

-- Re-assert the superuser role's grant, rather than relying on what the
-- translation happened to produce.
--
-- Translation alone leaves NEOTMS_SYSADMIN holding 35 of the 36
-- permissions: the legacy bootstrap gave it all five flags on every
-- active menu, which covers everything except PO_EMAIL, the one
-- permission that never had a flag behind it. A database freshly built
-- from 001 + 002 ends up with all 36, because the seed calls this same
-- function. One role, two row counts, depending on how the database was
-- built -- and the difference would be invisible until somebody compared
-- them.
--
-- This re-asserts the role's DEFINITION ("every permission this build
-- knows"); it does not discover anything. It cannot widen a real grant,
-- because the role already held every flag on every menu, and the one
-- permission it adds gates a feature that does not exist yet. It also
-- repairs the case where production's sys_menu is missing a row the
-- translation needed -- the superuser would otherwise come out of this
-- migration quietly short of a permission.
SELECT sys_role_grant_all_permissions('NEOTMS_SYSADMIN') AS permissions_granted;


-- =====================================================================
-- 3. Derive the user attributes from who is already named on the work
-- =====================================================================
--
-- Nothing in the old schema recorded who may be a 담당영업 or a 담당PM, so
-- there is no column to copy. What there is, is evidence: a person named
-- in project.prj_mgr_id has been acting as a sales manager, and a person
-- named in project.prj_pm_id or job.job_pm_id has been acting as a PM.
--
-- THIS IS NOT A CONVENIENCE. The server is about to start refusing a
-- prj_pm_id that names somebody without the PM attribute. Derived this
-- way, every project that exists today still validates tomorrow; derived
-- any other way -- or left empty for an administrator to fill in -- the
-- next edit of an old project fails on a field nobody touched.
--
-- Soft-deleted rows are included deliberately. A deleted project can be
-- the only evidence that somebody was a PM, and losing the attribute
-- because their last project was cancelled is not a decision this
-- migration should make.

INSERT INTO staff_attribute (staff_id, attribute, created_by)
SELECT DISTINCT p.prj_mgr_id, 'NEOTMS_USER_ATTRIBUTE_SALES_MANAGER', 'neotms-003-migration'
  FROM project p
 WHERE p.prj_mgr_id IS NOT NULL
ON CONFLICT (staff_id, attribute) DO NOTHING;

INSERT INTO staff_attribute (staff_id, attribute, created_by)
SELECT DISTINCT s.staff_id, 'NEOTMS_USER_ATTRIBUTE_PM', 'neotms-003-migration'
  FROM (
         SELECT prj_pm_id AS staff_id FROM project WHERE prj_pm_id IS NOT NULL
         UNION
         SELECT job_pm_id AS staff_id FROM job     WHERE job_pm_id IS NOT NULL
         UNION
         SELECT po_pm_id  AS staff_id FROM purchase_order WHERE po_pm_id IS NOT NULL
       ) s
ON CONFLICT (staff_id, attribute) DO NOTHING;

-- NEOTMS_USER_ATTRIBUTE_SUPERUSER is granted to NOBODY, deliberately. It
-- overrides every permission check, and the rule is that it only goes to
-- accounts holding `lpx.admin.access` -- which this database cannot see.
-- Section 4 checks that somebody can still administer users instead; the
-- way to grant it afterwards, to a person you have confirmed, is:
--
--   INSERT INTO staff_attribute (staff_id, attribute, created_by)
--   SELECT id, 'NEOTMS_USER_ATTRIBUTE_SUPERUSER', 'granted-by-hand'
--     FROM staff WHERE mgr_id = '<the mgr_id>'
--   ON CONFLICT DO NOTHING;


-- =====================================================================
-- 4. Refuse to finish if this would lock everybody out
-- =====================================================================
--
-- The failure this exists for: the flag mapping is wrong in a way that
-- drops STAFF_UPDATE, the application deploys, and the only screen that
-- could restore anyone's access is the one nobody can now open. There is
-- no way back from that inside the application -- it would take a hand
-- written INSERT against the live database.
--
-- So the migration aborts instead. An aborted migration is a rolled-back
-- transaction and an afternoon; the other outcome is an outage.

DO $$
DECLARE
  v_staff  integer;
  v_admins integer;
BEGIN
  SELECT count(*) INTO v_staff
    FROM staff s
   WHERE s.active AND NOT s.deleted;

  SELECT count(*) INTO v_admins
    FROM staff s
    JOIN sys_role_permission p ON p.role_id = s.role_id
   WHERE s.active
     AND NOT s.deleted
     AND p.permission = 'NEOTMS_PERMISSION_STAFF_UPDATE';

  -- A database with no people in it cannot lock anybody out, and it has a
  -- documented way in that does not depend on this migration at all:
  -- staff_bootstrap_superuser() admits the first authenticated LPX admin.
  -- Aborting here would block a legitimate run against a database that has
  -- been seeded but not yet loaded -- which is every staging database
  -- before its first ETL.
  IF v_staff = 0 THEN
    RAISE NOTICE
      'OK  no active staff rows yet, so nobody can be locked out. The first '
      'LPX admin to sign in gets a role through staff_bootstrap_superuser().';
  ELSIF v_admins = 0 THEN
    RAISE EXCEPTION
      'Refusing to finish: % active staff member(s) exist and NONE of them '
      'holds NEOTMS_PERMISSION_STAFF_UPDATE after translation, so nobody '
      'could administer users. Check section 5''s queries, especially the '
      'mixed-flag roles, and the STAFF rows of sys_role_auth.', v_staff;
  ELSE
    RAISE NOTICE 'OK  % of % active staff member(s) can administer users.',
      v_admins, v_staff;
  END IF;
END;
$$;

-- Everything above stands or falls together. Past this point the new model
-- is in place and the old tables are still there, which is the state the
-- application is deployed against.
COMMIT;


-- =====================================================================
-- 5. Verification -- read these before section 7
-- =====================================================================

-- 5a. Did anything in the matrix fail to translate? Any menu_id here is one
--     the application has no permission for. Legacy ETL menus are expected;
--     a NEOTMS menu in this list is a defect in section 2's mapping.
SELECT a.menu_id, count(*) AS grants_not_carried_across
  FROM sys_role_auth a
 WHERE a.active
   AND a.menu_id NOT IN ('PROJECT','JOB','PURCHASE_ORDER','CUSTOMER','TRANSLATOR',
                         'PAYMENT','MAINTENANCE','REPORT','DASHBOARD_SALES',
                         'DASHBOARD_PM','STAFF')
 GROUP BY a.menu_id
 ORDER BY a.menu_id;

-- 5b. THE ONE TO ACTUALLY READ. Every (role, menu) whose flags were MIXED --
--     these are the rows whose translation depended on the unconfirmed
--     ROLE_1..ROLE_5 mapping. A row with all five true is unambiguous and is
--     not listed. If this returns nothing, the mapping guess did not matter.
SELECT r.role_code,
       a.menu_id,
       a.role_1, a.role_2, a.role_3, a.role_4, a.role_5
  FROM sys_role_auth a
  JOIN sys_role r ON r.id = a.role_id
 WHERE a.active
   AND NOT (a.role_1 AND a.role_2 AND a.role_3 AND a.role_4 AND a.role_5)
   AND (a.role_1 OR a.role_2 OR a.role_3 OR a.role_4 OR a.role_5)
 ORDER BY r.role_code, a.menu_id;

-- 5c. What each role ended up with.
SELECT r.role_code, count(p.*) AS permissions
  FROM sys_role r
  LEFT JOIN sys_role_permission p ON p.role_id = r.id
 GROUP BY r.role_code
 ORDER BY r.role_code;

-- 5d. The derived attributes, and how many people hold each.
SELECT attribute, count(*) AS people
  FROM staff_attribute
 GROUP BY attribute
 ORDER BY attribute;

-- 5e. Any project whose named people would now fail validation. MUST BE
--     EMPTY -- section 3 derives the attributes from exactly these columns,
--     so a row here means a project references a staff row that no longer
--     exists, which was already broken before this migration.
SELECT p.prj_code,
       p.prj_mgr_id AS sales_manager_without_attribute,
       p.prj_pm_id  AS pm_without_attribute
  FROM project p
 WHERE (p.prj_mgr_id IS NOT NULL
        AND NOT EXISTS (SELECT 1 FROM staff_attribute a
                         WHERE a.staff_id = p.prj_mgr_id
                           AND a.attribute = 'NEOTMS_USER_ATTRIBUTE_SALES_MANAGER'))
    OR (p.prj_pm_id IS NOT NULL
        AND NOT EXISTS (SELECT 1 FROM staff_attribute a
                         WHERE a.staff_id = p.prj_pm_id
                           AND a.attribute = 'NEOTMS_USER_ATTRIBUTE_PM'))
 ORDER BY p.prj_code;


-- =====================================================================
-- 6. OPTIONAL -- narrow the two grants that were deliberately left broad
-- =====================================================================
--
-- Run these only after deciding who should hold them, and only after the
-- application is deployed and working. Both are commented out because a
-- migration that silently takes a capability away is the mirror image of
-- one that silently hands it out.
--
-- PROJECT_EMAIL currently belongs to everyone who can open a project,
-- because that is what sending a handover mail used to require. If it
-- should belong to the sales managers alone:
--
--   DELETE FROM sys_role_permission
--    WHERE permission = 'NEOTMS_PERMISSION_PROJECT_EMAIL'
--      AND role_id IN (SELECT id FROM sys_role WHERE role_code <> 'NEOTMS_SYSADMIN');
--
-- PO_APPROVE currently belongs to everyone who can record a payment,
-- because approving WAS that grant. Splitting the two is the whole reason
-- the permission exists -- "may sign off an amount" and "may confirm the
-- money left" are different jobs in most organisations:
--
--   DELETE FROM sys_role_permission
--    WHERE permission = 'NEOTMS_PERMISSION_PO_APPROVE'
