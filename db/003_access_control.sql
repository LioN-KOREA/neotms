-- =====================================================================
-- NEOTMS :: 003_access_control.sql
-- Moves a LIVE database from the menu x action matrix to named permissions.
-- =====================================================================
--
-- Run this ONCE, on a database that already has data. A database built from
-- 001_schemas.sql has the new shape already and must not be given this file
-- -- section 1 is harmless there, but sections 2 and 3 read tables 001 no
-- longer creates, and the run aborts.
--
-- WHAT CHANGES, AND WHAT MUST NOT
--
-- The point of a migration is that nobody's access changes. The permission
-- model changes shape; who can do what does not. Two of the new permissions
-- did not exist as grants before, and they are granted here to exactly the
-- people who could already perform the action:
--
--   * PO_APPROVE went to whoever held PAYMENT update, because approving a
--     purchase order WAS that grant.
--   * PROJECT_EMAIL went to whoever held PROJECT read, because sending a
--     handover mail WAS gated on being able to open the project.
--
-- Both of those grants are deliberately too broad -- that breadth is why
-- the two were split out in the first place. Narrowing them is a decision
-- for an administrator AFTER this runs, not something a migration should
-- do silently. Section 6 has the two statements, commented out, and says
-- what to look at before running them.
--
-- THE UNCONFIRMED FLAG MAPPING
--
-- The legacy columns are ROLE_1..ROLE_5 and the mapping to
-- read/create/update/delete/export was never verified against the ASP
-- source; 002_tables.sql said so in the column comments and this file
-- inherits the problem. It is handled rather than assumed:
--
--   * A row with ALL FIVE FLAGS TRUE translates the same way whatever the
--     mapping means, and that is what the seeded superuser role has. For
--     those rows there is no guess.
--   * A row with a MIXED pattern depends on the guess. Section 5 lists
--     every one of them so a human can check before anyone relies on it.
--
-- NOBODY GETS SUPERUSER
--
-- NEOTMS_USER_ATTRIBUTE_SUPERUSER overrides every permission check, and
-- the rule is that it only goes to accounts holding `lpx.admin.access` --
-- which this database cannot see. So the migration grants it to nobody and
-- section 4 instead ABORTS if the translation would leave no active person
-- able to administer users. Failing the migration is recoverable; handing
-- out an override nobody asked for is not.
--
-- =====================================================================


-- =====================================================================
-- 1. The new tables, the vocabulary, and the grant function
-- =====================================================================
--
-- Identical to what 001_schemas.sql creates on a fresh database. Written
-- with IF NOT EXISTS so that a database which has already been moved can
-- be given this file again without harm.

-- Sections 1 to 4 are ONE transaction, explicitly, because section 4's
-- abort has to be able to undo sections 1 to 3. psql commits each
-- statement on its own unless told otherwise, so without this BEGIN the
-- abort would leave a half-migrated database -- new tables, translated
-- grants, and no way for anyone to administer users. That is the exact
-- state section 4 exists to prevent, so the transaction is part of the
-- check, not a precaution around it.
--
-- DDL is transactional in PostgreSQL, so the CREATE TABLEs roll back too.
--
-- If you run this with `psql -1`, or paste it into the Supabase SQL editor,
-- there is already a transaction open and you will see two warnings:
--
--   WARNING:  there is already a transaction in progress   (at this BEGIN)
--   WARNING:  there is no transaction in progress          (at the end)
--
-- Both are cosmetic and both outcomes were rehearsed: the grants come out
-- identical, and an abort still rolls everything back. Unlike 001 and 002 --
-- which carry no transaction control precisely because the editor supplies
-- its own -- this file states it explicitly, because a half-applied data
-- migration is a worse failure than a warning is a nuisance.
BEGIN;

