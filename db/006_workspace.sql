-- =====================================================================
-- NEOTMS :: 006_workspace.sql
-- Adds the 나의 업무 workspace to a database that already has data.
-- =====================================================================
--
-- Two tables, two indexes, one permission and one sidebar row. Nothing to
-- migrate and no point of no return -- everything here is additive and
-- re-runnable, so a run interrupted halfway can simply be repeated.
--
-- A database built from db/001_schemas.sql has the tables and the
-- permission already, and db/002_initial_seeding.sql has the menu row.
-- Giving a fresh database this file is harmless but unnecessary.
--
-- APPLY THIS BEFORE THE DEPLOY. GET /api/v0/workspace selects from both
-- tables, so until they exist the screen answers 42P01 -- and the
-- permission CHECK below has to accept NEOTMS_PERMISSION_WORKSPACE_READ
-- before anybody can be granted it, or the grant fails with 23514 and
-- the sidebar entry never appears for anyone.
--
-- WHAT IT IS FOR
--
-- 나의 업무 is one PM's own worksheet -- every purchase order under a
-- project they have accepted, as a spreadsheet. Fourteen columns are
-- fixed and come from the project, job and PO rows; editing one of the
-- editable ones writes through to that row by the same endpoint the
-- forms use. Everything in THIS file is the other half: the columns a
-- person adds for themselves, and what they type into them.
--
-- WHY RELATIONAL AND NOT A JSON DOCUMENT PER USER
--
-- The deciding requirement was that a value disappears when its PO does.
-- Here that is a foreign key. As a per-user document it is an
-- orphan-reaping job to write, schedule and watch, and until it runs the
-- values of deleted POs are still stored and still paid for.
--
-- Three more point the same way. The sheet's rows are scoped by SQL
-- already, so the values come back attached to their row in the same
-- statement. A spreadsheet writes ONE cell at a time, which is one row
-- here against a read-modify-write of a whole document -- two open tabs
-- would silently overwrite each other. And a document has a size ceiling
-- the sheet grows into, which fails at save time, just after somebody
-- typed something.
--
-- WHAT A MISSING FILE LOOKS LIKE
--
-- The sidebar entry is absent (no sys_menu row, and nobody holds the
-- permission) and GET /api/v0/workspace answers 500 with 42P01 in the
-- log. No other screen changes: nothing outside /api/v0/workspace reads
-- either table.
--
-- =====================================================================

BEGIN;


-- ---------------------------------------------------------------------
-- 1. The two tables
-- ---------------------------------------------------------------------
-- Column definitions and cell values, both private to one staff id.
--
-- ON DELETE CASCADE three times over, which is unusual in this schema
-- and deliberate each time. staff -- a departed employee's private
-- annotations are not company history the way their projects are, the
-- same judgement staff_recent_search makes. workspace_column -- deleting
-- a column destroys its values, which is what the feature promises the
-- person who deletes it. purchase_order -- a hard-deleted PO takes its
-- annotations with it, there being nothing left to annotate.

CREATE TABLE IF NOT EXISTS workspace_column (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id   bigint NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
  col_label  text NOT NULL,
  ord_no     integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz,
  created_by text,
  created_ip inet,
  CONSTRAINT ck_workspace_column_label CHECK (char_length(col_label) BETWEEN 1 AND 40)
);

CREATE TABLE IF NOT EXISTS workspace_cell (
  column_id  bigint NOT NULL REFERENCES workspace_column (id) ON DELETE CASCADE,
  po_id      bigint NOT NULL REFERENCES purchase_order (id) ON DELETE CASCADE,
  cell_text  text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (column_id, po_id),
  CONSTRAINT ck_workspace_cell_text CHECK (char_length(cell_text) <= 2000)
);

-- Sheet order for one person, and every annotation on one PO. The primary
-- key leads with column_id, so the second direction would otherwise scan.
CREATE INDEX IF NOT EXISTS ix_workspace_column_staff ON workspace_column (staff_id, ord_no, id);
CREATE INDEX IF NOT EXISTS ix_workspace_cell_po ON workspace_cell (po_id);

COMMENT ON TABLE  workspace_column IS
  'One custom column on one person''s 나의 업무 sheet. NEOTMS only -- no legacy table. Private to its staff_id: every read and write goes through /api/v0/workspace scoped to the caller, and no other screen reads this table.';
COMMENT ON COLUMN workspace_column.col_label IS
  'The column heading the person typed. Free text on purpose -- the requirement was "freely editable", and a typed column would mean a spreadsheet that refuses what was typed into it.';
COMMENT ON COLUMN workspace_column.ord_no IS
  'Left-to-right position among the custom columns. Not UNIQUE per staff member: a reorder rewrites every row in one statement, and a unique constraint would make the intermediate state of that rewrite illegal. Ties break on id.';
COMMENT ON TABLE  workspace_cell IS
  'One value in one custom column, against one purchase order. NEOTMS only. The composite primary key IS the "one value per column per row" rule, so a save is an upsert rather than a read-then-insert.';
COMMENT ON COLUMN workspace_cell.po_id IS
  'The purchase order this value is attached to. NOTE -- NEOTMS soft-deletes, so a deleted PO''s values stop being VISIBLE because the sheet no longer has that row, not because this cascade fired; the cascade covers a hard delete or an ETL purge. An undeleted PO brings its values back, which is intended rather than accidental.';
COMMENT ON COLUMN workspace_cell.cell_text IS
  'The value, always as text. One column rather than a typed triple because every custom column is free text.';


-- ---------------------------------------------------------------------
-- 2. The permission vocabulary
-- ---------------------------------------------------------------------
-- NEOTMS_PERMISSION_WORKSPACE_READ has to be in the CHECK before it can
-- be granted, and PostgreSQL has no ADD CONSTRAINT IF NOT EXISTS -- hence
-- the drop, the NOT VALID add and the VALIDATE. VALIDATE is a no-op on an
-- already-valid constraint, which is what makes the block re-runnable.
--
-- The list below is the whole vocabulary, not just the new name: a CHECK
-- cannot be extended in place. It is generated from the one in
-- db/001_schemas.sql rather than typed again, so the two cannot disagree
-- -- and they must not, because sys_role_grant_all_permissions() reads
-- this constraint out of the catalogue to decide what "every permission"
-- means.

ALTER TABLE sys_role_permission DROP CONSTRAINT IF EXISTS ck_sys_role_permission;
ALTER TABLE sys_role_permission
  ADD CONSTRAINT ck_sys_role_permission CHECK (permission IN (
  'NEOTMS_PERMISSION_PROJECT_READ',
  'NEOTMS_PERMISSION_PROJECT_CREATE',
  'NEOTMS_PERMISSION_PROJECT_UPDATE',
  'NEOTMS_PERMISSION_PROJECT_DELETE',
  'NEOTMS_PERMISSION_PROJECT_EMAIL',
  'NEOTMS_PERMISSION_JOB_READ',
  'NEOTMS_PERMISSION_JOB_CREATE',
  'NEOTMS_PERMISSION_JOB_UPDATE',
  'NEOTMS_PERMISSION_JOB_DELETE',
  'NEOTMS_PERMISSION_PO_READ',
  'NEOTMS_PERMISSION_PO_CREATE',
  'NEOTMS_PERMISSION_PO_UPDATE',
  'NEOTMS_PERMISSION_PO_DELETE',
  'NEOTMS_PERMISSION_PO_APPROVE',
  'NEOTMS_PERMISSION_PO_EMAIL',
  'NEOTMS_PERMISSION_TRANSLATOR_READ',
  'NEOTMS_PERMISSION_TRANSLATOR_CREATE',
  'NEOTMS_PERMISSION_TRANSLATOR_UPDATE',
  'NEOTMS_PERMISSION_TRANSLATOR_DELETE',
  'NEOTMS_PERMISSION_INVOICE_READ',
  'NEOTMS_PERMISSION_INVOICE_CREATE',
  'NEOTMS_PERMISSION_INVOICE_UPDATE',
  'NEOTMS_PERMISSION_INVOICE_DELETE',
  'NEOTMS_PERMISSION_CUSTOMER_READ',
  'NEOTMS_PERMISSION_CUSTOMER_CREATE',
  'NEOTMS_PERMISSION_CUSTOMER_UPDATE',
  'NEOTMS_PERMISSION_CUSTOMER_DELETE',
  'NEOTMS_PERMISSION_REPORT_READ',
  'NEOTMS_PERMISSION_DASHBOARD_SALES_READ',
  'NEOTMS_PERMISSION_DASHBOARD_PM_READ',
  'NEOTMS_PERMISSION_MAINTENANCE_READ',
  'NEOTMS_PERMISSION_MAINTENANCE_CREATE',
  'NEOTMS_PERMISSION_MAINTENANCE_UPDATE',
  'NEOTMS_PERMISSION_MAINTENANCE_DELETE',
  'NEOTMS_PERMISSION_STAFF_READ',
  'NEOTMS_PERMISSION_STAFF_UPDATE',
  'NEOTMS_PERMISSION_WORKSPACE_READ'
  )) NOT VALID;
ALTER TABLE sys_role_permission VALIDATE CONSTRAINT ck_sys_role_permission;


-- ---------------------------------------------------------------------
-- 3. The sidebar row
-- ---------------------------------------------------------------------
-- ord_no 12, continuing 결제 at 11. DO NOTHING rather than DO UPDATE, the
-- same rule every other menu seed follows -- re-running must not reset a
-- label an operator has corrected.
--
-- sys_menu is navigation only. A screen is shown when its read permission
-- is held, so this row is what somebody reading the database sees rather
-- than what the application gates on.

INSERT INTO sys_menu (menu_id, menu_name, menu_parent, menu_depth, menu_url, ord_no, active)
VALUES
  ('WORKSPACE', '나의 업무', NULL, 1, '/workspace', 12, true)
ON CONFLICT (menu_id) DO NOTHING;


-- ---------------------------------------------------------------------
-- 4. Re-grant the superuser role
-- ---------------------------------------------------------------------
-- The half that is easy to leave out, and whose absence is worse than
-- forgetting the INSERT: with the menu row but no re-grant the superuser
-- sees 나의 업무 in the sidebar and gets 403 from it, which reads as a
-- broken feature rather than a missing one.
--
-- Grants written once do not cover permissions added later, and this file
-- adds one. The call is idempotent, so running it again is the correct
-- response to any doubt.

SELECT sys_role_grant_all_permissions('NEOTMS_SYSADMIN') AS permissions_granted;

COMMIT;


-- =====================================================================
-- VERIFY
-- =====================================================================
-- Run these after applying. Expected results are in the comments.

-- Both tables exist, with the three cascades.
SELECT c.conrelid::regclass AS child,
       c.confrelid::regclass AS parent,
       c.confdeltype          AS on_delete
  FROM pg_constraint c
 WHERE c.contype = 'f'
   AND c.conrelid::regclass::text IN ('workspace_column', 'workspace_cell')
 ORDER BY 1, 2;
-- Expect three rows, on_delete = 'c' on every one of them.

-- The superuser can now be granted the new permission, and has been.
SELECT count(*) AS sysadmin_holds_workspace_read
  FROM sys_role_permission rp
  JOIN sys_role r ON r.id = rp.role_id
 WHERE r.role_code = 'NEOTMS_SYSADMIN'
   AND rp.permission = 'NEOTMS_PERMISSION_WORKSPACE_READ';
-- Expect 1. A 0 here means section 4 did not run.

-- Nobody has annotations yet, and no annotation points at a dead PO.
SELECT (SELECT count(*) FROM workspace_column) AS columns_defined,
       (SELECT count(*) FROM workspace_cell)   AS cells_stored,
       (SELECT count(*)
          FROM workspace_cell wc
          JOIN purchase_order po ON po.id = wc.po_id
         WHERE po.deleted)                     AS cells_on_deleted_pos;
-- Expect 0, 0, 0 on a first run. On a later run the third stays the
-- interesting one: those rows are invisible in the sheet but still stored,
-- which is the soft-delete behaviour the table comment describes.
