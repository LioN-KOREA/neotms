-- =====================================================================
-- NEOTMS :: 004_recent_searches.sql
-- Adds staff_recent_search to a database that already has data.
-- =====================================================================
--
-- One table, no data to migrate. Everything here is additive and
-- re-runnable, so a run interrupted halfway can simply be repeated.
--
-- Unlike 003_access_control.sql there is no point of no return in this
-- file and nothing to read before deploying: the application writes the
-- table when somebody searches and reads it when a list screen opens.
-- Until it exists both of those answer 42P01, which is why this applies
-- BEFORE the deploy rather than after it.
--
-- A database built from db/001_schemas.sql has this table already. Giving
-- it this file is harmless -- every statement is IF NOT EXISTS -- but it
-- is not needed.
--
-- WHAT IT IS FOR
--
-- The last five search terms each person typed on each list screen,
-- offered back to them as suggestions in that screen's search box. It is
-- the only table in the schema that is private to one person: every row
-- is read and written through /api/v0/me/recent-searches, scoped to the
-- caller's own staff id, and nothing joins it to anything.
--
-- It is also the only table that is safe to truncate. The consequence of
-- losing every row is an empty suggestion list.
--
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS staff_recent_search (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id   bigint NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
  scope      text NOT NULL,
  term       text NOT NULL,
  used_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_staff_recent_search UNIQUE (staff_id, scope, term),
  /*
   * The screens that have a search box, named by their own route path so there is no second
   * naming scheme to keep in step. A CHECK rather than a free text column because the scope
   * arrives from the client: without it, a typo'd or invented scope writes rows that no screen
   * ever reads back, and the symptom is "my recent searches are empty" with data in the table.
   */
  CONSTRAINT ck_staff_recent_search_scope CHECK (scope IN (
    'projects',
    'jobs',
    'purchase-orders',
    'customers',
    'translators',
    'payment/purchase-orders',
    'payment/invoices'
  )),
  /*
   * Bounded here as well as in the request schema. This column exists to be offered back to the
   * person as a suggestion, and a 4,000-character "search term" pasted by accident would be a
   * suggestion nobody can read and a row nobody can get rid of from the UI.
   */
  CONSTRAINT ck_staff_recent_search_term CHECK (char_length(term) BETWEEN 1 AND 100)
);

-- ON DELETE CASCADE above, and no soft delete anywhere here: this is the
-- one table whose rows have no meaning once the person is gone. Every
-- other table keeps a departed employee's rows because the work they did
-- is company history; nobody needs to know what a leaver used to search
-- for, and `created_by` audit values point at people, not at this table.

COMMENT ON TABLE  staff_recent_search IS
  'The last few search terms each person used on each list screen, offered back to them as suggestions. Convenience data, and the only table in this schema that is private to one person: every row is read and written through /api/v0/me/recent-searches, scoped to the caller''s own staff id, and nothing else joins it. Five rows per person per scope are kept -- the write prunes the rest, so this table does not grow with use. Safe to truncate: the consequence is an empty suggestion list.';
COMMENT ON COLUMN staff_recent_search.scope IS
  'Which list the term was typed on, named by that screen''s route path (''projects'', ''payment/invoices''). The permitted values are the CHECK above.';
COMMENT ON COLUMN staff_recent_search.term IS
  'The search term as typed, trimmed. UNIQUE per person and scope, so re-running the same search moves it to the top (used_at is bumped) rather than filling the list with one term.';
COMMENT ON COLUMN staff_recent_search.used_at IS
  'When it was last searched. The suggestion order, and what the five-row prune keeps.';

-- One person's recent searches on one screen, newest first -- which is the only way this table is
-- ever read, and the order the five-row prune needs. `id DESC` after `used_at DESC` because two
-- searches in the same instant would otherwise tie, and a prune with a tie can keep the wrong five.
CREATE INDEX IF NOT EXISTS ix_recent_search_recent
  ON staff_recent_search (staff_id, scope, used_at DESC, id DESC);

COMMIT;


-- =====================================================================
-- Verification
-- =====================================================================

-- Must report the seven scopes the application writes. A scope missing here
-- is a screen whose searches will be refused with a 23514.
-- The same shape neotms_known_permissions() uses in 001 to read its own CHECK: pull the quoted
-- literals back out of the constraint definition. Deliberately not a hand-written list -- a second
-- copy of the scopes is a second thing to forget.
SELECT m[1] AS permitted_scope
  FROM pg_constraint c,
       LATERAL regexp_matches(pg_get_constraintdef(c.oid), '''([a-z/-]+)''', 'g') AS m
 WHERE c.conrelid = 'staff_recent_search'::regclass
   AND c.conname  = 'ck_staff_recent_search_scope'
 ORDER BY 1;

-- Must be 0 on a database that has just had this applied, and must stay
-- at or below 5 per person per scope afterwards. A number above 5 means
-- the prune in NeotmsRecentSearchManager stopped running.
SELECT coalesce(max(kept), 0) AS most_rows_for_one_person_and_scope
  FROM (SELECT count(*) AS kept
          FROM staff_recent_search
         GROUP BY staff_id, scope) counts;
