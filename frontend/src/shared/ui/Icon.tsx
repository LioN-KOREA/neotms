/**
 * 인라인 SVG 아이콘.
 *
 * ## 아이콘 패키지를 쓰지 않는 이유
 *
 * 이 파일이 필요한 만큼은 20여 개이고, `lucide-react` 나 `react-icons` 는 그 20개를 위해
 * 수천 개가 든 패키지를 의존성에 추가한다. 트리 셰이킹으로 번들에서 빠진다 해도 남는 비용이
 * 둘 있다 — `npm ci` 가 매번 그걸 받고, 아이콘 패키지의 메이저 업그레이드가 이 앱의 빌드를
 * 깨뜨릴 수 있다. 콘솔은 S3 에 올라가는 정적 파일이고 빌드가 단순할수록 좋다.
 *
 * 설계안(neoTMS_UI_Design.pdf)도 같은 선택을 명시한다: "모든 그래픽은 인라인 SVG — 외부
 * 리소스 의존 없음".
 *
 * ## 모든 path 가 stroke 로 그려진다
 *
 * `fill="none"` + `stroke="currentColor"` 로 통일했다. 색을 `currentColor` 로 두면 아이콘이
 * 놓인 자리의 글자색을 그대로 따라가므로, 레일의 비활성(회보라)·활성(흰색)·본문(잉크색)에
 * 각각 쓸 아이콘을 따로 만들 필요가 없다. 채움(fill) 아이콘을 섞으면 그 규칙이 깨져서
 * 비활성 상태에서 혼자 진하게 보인다.
 *
 * `strokeWidth` 는 1.6 고정이다. 16px 과 20px 양쪽에서 쓰는데, 2 는 16px 에서 뭉치고 1.2 는
 * 20px 에서 흐려진다.
 */

