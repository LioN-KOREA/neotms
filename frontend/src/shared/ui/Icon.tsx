interface Props extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName
  /** 한 변의 px. 기본 16 — 본문 13px 옆에 섰을 때 글자 높이와 비슷해지는 크기다. */
  size?: number
}

/**
 * 하나의 아이콘.
 *
 * `aria-hidden` 이 기본값인 것은 의도다. 이 앱의 아이콘은 거의 전부 **글자 옆에 붙는 장식**이고
 * (레일 메뉴, 버튼), 그 경우 아이콘까지 읽히면 스크린 리더가 같은 뜻을 두 번 말한다. 글자 없이
 * 아이콘만 두는 자리(닫기 버튼 등)에서는 아이콘이 아니라 **감싸는 버튼** 쪽에 `aria-label` 을
 * 준다 — 그래야 포커스를 받는 요소와 이름이 같은 요소가 일치한다.
 */
export function Icon({ name, size = 16, ...rest }: Props) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {PATHS[name].map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  )
}
